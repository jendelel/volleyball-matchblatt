  /**
   * Translate a key into `lang` ('en' | 'de') with `{var}` placeholder interpolation.
   * Falls back to English if missing in target language, and then to `params.fallback || key`.
   *
   * @param {string} key
   * @param {string} [lang='en']
   * @param {Record<string, any>} [params={}]
   * @returns {string}
   */
  function t(key, lang, params) {
    var safeLang = lang && DICTIONARY[lang] ? lang : 'en';
    var opts = params && typeof params === 'object' ? params : {};
    var strKey = String(key || '');

    var template = DICTIONARY[safeLang][strKey];
    if (template === undefined && safeLang !== 'en') {
      template = DICTIONARY.en[strKey];
    }
    if (template === undefined) {
      template = opts.fallback !== undefined ? String(opts.fallback) : strKey;
    }

    return template.replace(/\{(\w+)\}/g, function (match, varName) {
      return Object.prototype.hasOwnProperty.call(opts, varName) && opts[varName] !== undefined && opts[varName] !== null
        ? String(opts[varName])
        : match;
    });
  }

  function hasKey(key, lang) {
    var safeLang = lang && DICTIONARY[lang] ? lang : 'en';
    return Object.prototype.hasOwnProperty.call(DICTIONARY[safeLang], key);
  }

